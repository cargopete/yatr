//! `yatr agents`: the section of AGENTS.md that tells a coding agent how to
//! use a project's tasks, generated from the config so it cannot drift.

use std::fmt::Write as _;
use std::path::Path;

use crate::config::{Config, TaskConfig};
use crate::error::{Result, YatrError};
use crate::graph::TaskGraph;

pub const BEGIN: &str = "<!-- yatr:begin -->";
pub const END: &str = "<!-- yatr:end -->";

const fn is_aggregate(task: &TaskConfig) -> bool {
    task.run.is_empty() && task.script.is_none() && task.wasm.is_none()
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

const fn notes(task: &TaskConfig, cache_on: bool) -> &'static str {
    if is_aggregate(task) {
        "runs its dependencies only"
    } else if task.foreground {
        "long-running: start it in the background, do not wait for it to exit"
    } else if cache_on && !task.no_cache && !task.sources.is_empty() {
        "cached on its inputs"
    } else {
        "always runs"
    }
}

/// The section, from its opening marker to its closing one. `file` is where
/// it is kept, when that is not `AGENTS.md`, so the section can say how to
/// regenerate itself.
#[must_use]
pub fn section(
    config: &Config,
    graph: &TaskGraph,
    config_name: &str,
    file: Option<&str>,
) -> String {
    let mut names: Vec<&str> = graph.task_names().collect();
    names.sort_unstable();
    let write = file.map_or_else(
        || "yatr agents --write".to_string(),
        |file| format!("yatr agents --write {file}"),
    );

    let mut out = format!(
        "{BEGIN}\n\
         <!-- Generated by `{write}` from {config_name}. Edit that file, not this section. -->\n\
         ## Tasks\n\n\
         This project's build, test and lint commands are [yatr](https://github.com/cargopete/yatr) \
         tasks, defined in `{config_name}`. Run them through yatr rather than calling the tools \
         directly: a task whose inputs have not changed is restored from cache instead of run again.\n\n\
         - `yatr run --agent <task>...` runs tasks and prints one line per task. For a failure it \
         adds the failing command, its exit code and the last lines of its output; the whole \
         output is in `.yatr/logs/<task>.log`.\n"
    );
    if names.contains(&"ci") {
        out.push_str(
            "- Before reporting work as done, run `yatr run --agent ci` and fix what it reports.\n",
        );
    }
    out.push_str(
        "- `yatr explain <task>` says whether a task would run or come from cache, and which \
         inputs changed.\n\
         - `yatr affected <git-ref>` lists the tasks that changes since a ref can affect.\n\
         - `yatr run --json <task>...` and `yatr list --format json` are the machine-readable forms.\n",
    );
    let _ = write!(
        out,
        "- To add or change a task, edit `{config_name}`, then run `yatr check` and \
         `{write}`.\n\n\
         | Task | What it does | Runs after | Notes |\n\
         |---|---|---|---|\n"
    );
    for name in names {
        let Some(task) = config.get_task(name) else {
            continue;
        };
        let deps = graph.dependencies(name).unwrap_or_default();
        let after = if deps.is_empty() {
            String::new()
        } else {
            deps.iter()
                .map(|d| format!("`{d}`"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "| `{name}` | {} | {after} | {} |",
            cell(task.desc.as_deref().unwrap_or_default()),
            notes(task, config.settings.cache),
        );
    }
    out.push_str(END);
    out.push('\n');
    out
}

/// The section as it stands in `document`, markers included, if it has one.
fn existing(document: &str) -> Option<(usize, usize)> {
    let start = document.find(BEGIN)?;
    let end = start + document[start..].find(END)? + END.len();
    let end = end + usize::from(document[end..].starts_with('\n'));
    Some((start, end))
}

/// `document` with the section replaced, or appended if it had none.
#[must_use]
pub fn merged(document: &str, section: &str) -> String {
    match existing(document) {
        Some((start, end)) => format!("{}{section}{}", &document[..start], &document[end..]),
        None if document.trim().is_empty() => section.to_string(),
        None => format!("{}\n\n{section}", document.trim_end()),
    }
}

/// Write the section into `path`, creating the file if need be. Returns
/// whether the file changed.
pub fn write(path: &Path, section: &str) -> Result<bool> {
    let before = match std::fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(e.into()),
    };
    let after = merged(&before, section);
    if after == before {
        return Ok(false);
    }
    std::fs::write(path, after)?;
    Ok(true)
}

/// Fail unless `path` holds exactly this section.
pub fn check(path: &Path, section: &str) -> Result<()> {
    let stale = |what: &str| YatrError::AgentsStale {
        message: format!(
            "{} {what}; write it again with `yatr agents --write{}`",
            path.display(),
            if path.file_name().is_some_and(|n| n == "AGENTS.md") {
                String::new()
            } else {
                format!(" {}", path.display())
            }
        ),
    };
    let document = match std::fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Err(stale("does not exist")),
        Err(e) => return Err(e.into()),
    };
    match existing(&document) {
        None => Err(stale("has no yatr section")),
        Some((start, end)) if document[start..end].trim_end() != section.trim_end() => {
            Err(stale("is out of date with the task definitions"))
        }
        Some(_) => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn merged_appends_then_replaces_in_place() {
        let first = format!("{BEGIN}\none\n{END}\n");
        let second = format!("{BEGIN}\ntwo\n{END}\n");

        let doc = merged("# Notes\n\nKeep me.\n", &first);
        assert_eq!(doc, format!("# Notes\n\nKeep me.\n\n{first}"));

        let doc = merged(&format!("{doc}\nAnd me.\n"), &second);
        assert_eq!(doc, format!("# Notes\n\nKeep me.\n\n{second}\nAnd me.\n"));
        assert_eq!(merged(&doc, &second), doc);
    }

    #[test]
    fn merged_into_nothing_is_the_section() {
        let section = format!("{BEGIN}\none\n{END}\n");
        assert_eq!(merged("", &section), section);
    }
}
